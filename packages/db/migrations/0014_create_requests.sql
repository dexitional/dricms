-- Submissions of the DRIC request forms (intent to submit, letter of support,
-- proposal review, project close-out, equipment transfer). Fields every form
-- shares are columns; type-specific answers live in `data`, table rows (the
-- equipment list) in `items`.
CREATE TABLE requests (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  reference VARCHAR(20) NOT NULL,
  access_key CHAR(32) NOT NULL,
  type ENUM('INTENT','SUPPORT_LETTER','PROPOSAL_REVIEW','CLOSE_OUT','EQUIPMENT_TRANSFER') NOT NULL,
  status ENUM('SUBMITTED','RECEIVED','UNDER_REVIEW','APPROVED','DECLINED') NOT NULL DEFAULT 'SUBMITTED',
  surname VARCHAR(80) NOT NULL,
  first_name VARCHAR(80) NOT NULL,
  middle_name VARCHAR(120) NULL,
  college VARCHAR(150) NULL,
  faculty VARCHAR(150) NULL,
  department VARCHAR(150) NULL,
  designation VARCHAR(120) NULL,
  email VARCHAR(150) NOT NULL,
  phone VARCHAR(40) NULL,
  call_link VARCHAR(500) NULL,
  project_title VARCHAR(300) NOT NULL,
  funding_agencies VARCHAR(500) NULL,
  funder_emails VARCHAR(500) NULL,
  data JSON NULL,
  items JSON NULL,
  attachments JSON NULL,
  project_id INT UNSIGNED NULL,
  investigator_id INT UNSIGNED NULL,
  signed_name VARCHAR(150) NULL,
  signed_at DATE NULL,
  received_at DATE NULL,
  official_condition TEXT NULL,
  director_decision TEXT NULL,
  director_name VARCHAR(150) NULL,
  director_decided_at DATE NULL,
  vc_decision TEXT NULL,
  vc_name VARCHAR(150) NULL,
  vc_decided_at DATE NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_requests_reference (reference),
  KEY idx_requests_type_status (type, status),
  KEY idx_requests_email (email),
  CONSTRAINT fk_requests_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE SET NULL,
  CONSTRAINT fk_requests_investigator FOREIGN KEY (investigator_id) REFERENCES investigators (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
