CREATE TABLE activities (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  phase_id INT UNSIGNED NOT NULL,
  title VARCHAR(255) NOT NULL,
  description TEXT NULL,
  subjects VARCHAR(500) NULL,
  amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  currency CHAR(3) NOT NULL DEFAULT 'USD',
  location VARCHAR(200) NULL,
  status ENUM('PLANNED','ONGOING','COMPLETED') NOT NULL DEFAULT 'PLANNED',
  start_date DATE NULL,
  end_date DATE NULL,
  report TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_activities_phase (phase_id),
  CONSTRAINT fk_activities_phase FOREIGN KEY (phase_id) REFERENCES phases (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
