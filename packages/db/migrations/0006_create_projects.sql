CREATE TABLE projects (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  code VARCHAR(20) NOT NULL,
  title VARCHAR(300) NOT NULL,
  description TEXT NULL,
  total_funding DECIMAL(15,2) NOT NULL DEFAULT 0,
  currency CHAR(3) NOT NULL DEFAULT 'USD',
  type ENUM('PROJECT','CONSULTANCY') NOT NULL DEFAULT 'PROJECT',
  status ENUM('ONGOING','COMPLETED','CLOSED','SUSPENDED') NOT NULL DEFAULT 'ONGOING',
  awarded_at DATE NULL,
  start_date DATE NULL,
  end_date DATE NULL,
  country_id SMALLINT UNSIGNED NULL,
  funder_id INT UNSIGNED NULL,
  pi_id INT UNSIGNED NULL,
  final_report MEDIUMTEXT NULL,
  contract_url VARCHAR(500) NULL,
  contract_name VARCHAR(255) NULL,
  budget_url VARCHAR(500) NULL,
  budget_name VARCHAR(255) NULL,
  created_by INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_projects_code (code),
  KEY idx_projects_status (status),
  CONSTRAINT fk_projects_country FOREIGN KEY (country_id) REFERENCES countries (id) ON DELETE SET NULL,
  CONSTRAINT fk_projects_funder FOREIGN KEY (funder_id) REFERENCES funders (id) ON DELETE SET NULL,
  CONSTRAINT fk_projects_pi FOREIGN KEY (pi_id) REFERENCES investigators (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
